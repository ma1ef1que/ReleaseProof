import generatedFixture from "../../test-fixtures/playwright-json/generated.json";
import unknownStatusFixture from "../../test-fixtures/playwright-json/unknown-status.json";
import zeroTestsFixture from "../../test-fixtures/playwright-json/zero-tests.json";
import { describe, expect, it } from "vitest";
import type { NormalizedReport, TestStatus } from "../../domain/report";
import { calculateEvidenceStatus } from "../evidence/evidence-rules";
import { createStableId } from "../../lib/ids";
import {
  playwrightJsonReportSchema,
  type PlaywrightJsonReport,
} from "./playwright-json-schema";
import {
  mapPlaywrightStatus,
  normalizePlaywrightReport,
  parsePlaywrightJson,
  type ReportParseError,
} from "./playwright-normalizer";

const fixtureOptions = {
  sourceFileName: "generated.json",
  importedAt: "2026-10-29T12:00:00.000Z",
};

function requireReport(result: ReturnType<typeof parsePlaywrightJson>) {
  if (!result.ok) {
    throw new Error(result.error.message);
  }
  return result.report;
}

function requireError(result: ReturnType<typeof parsePlaywrightJson>) {
  if (result.ok) {
    throw new Error("Expected report parsing to fail.");
  }
  return result.error satisfies ReportParseError;
}

function firstResult(report: PlaywrightJsonReport) {
  const result = report.suites[0]?.specs?.[0]?.tests?.[0]?.results?.[0];
  if (!result) {
    throw new Error("Generated fixture has no first result.");
  }
  return result;
}

describe("Playwright JSON boundary and normalization", () => {
  it("normalizes a report generated by the supported Playwright reporter", () => {
    const report = requireReport(
      normalizePlaywrightReport(generatedFixture, fixtureOptions),
    );

    expect(report.metadata.playwrightVersion).toBe("1.64.1");
    expect(report.metadata.runOutcome).toBe("passed");
    expect(report.tests.map((test) => test.status)).toEqual([
      "passed",
      "flaky",
      "skipped",
      "expectedToFail",
    ]);
    expect(report.tests[0]?.fullTitle).toBe("report.spec.ts › passes normally");
    expect(report.aggregate).toMatchObject({
      totalLogicalTests: 4,
      passed: 1,
      flaky: 1,
      skipped: 1,
      expectedToFail: 1,
      totalAttempts: 5,
    });
    expect(report.aggregate.totalAttemptDurationMs).toBeGreaterThan(0);
    expect(report.tests[1]?.retryCount).toBe(1);
    expect(report.tests[1]?.durationMs).toBe(
      report.tests[1]?.attempts.reduce(
        (duration, attempt) => duration + (attempt.durationMs ?? 0),
        0,
      ),
    );
    expect(report.tests[1]?.attempts.map((attempt) => attempt.status)).toEqual([
      "failed",
      "passed",
    ]);
    expect(report.tests[1]?.attempts[0]?.errorMessages[0]).toContain(
      "toBeGreaterThan",
    );
    expect(report.tests[1]?.attempts[0]?.stackTraceText).toContain(
      "report.spec.ts",
    );
    expect(report.tests[1]?.attachments[0]).toMatchObject({
      kind: "text",
      missing: true,
    });
    expect(report.evidence.status).toBe("review_required");
  });

  it("returns safe categories for empty, malformed, and unsupported input", () => {
    expect(requireError(parsePlaywrightJson("  "))).toMatchObject({
      category: "empty",
    });
    expect(requireError(parsePlaywrightJson("{not json"))).toMatchObject({
      category: "malformed",
      message: "The selected file is not valid JSON.",
    });
    expect(requireError(normalizePlaywrightReport({}))).toMatchObject({
      category: "unsupported",
      message: "This Playwright report version or format is not supported yet.",
    });
  });

  it("maps known statuses and visibly preserves unknown statuses", () => {
    for (const status of [
      "passed",
      "failed",
      "skipped",
      "timedOut",
      "interrupted",
      "flaky",
      "expectedToFail",
    ] as const) {
      expect(mapPlaywrightStatus(status)).toBe(status);
    }
    expect(mapPlaywrightStatus("futureStatus")).toBe("unknown");

    const result = requireReport(
      normalizePlaywrightReport(unknownStatusFixture, fixtureOptions),
    );
    expect(result.tests[0]?.status).toBe("unknown");
    expect(result.metadata.warnings).toContain(
      'Unsupported test status "futureStatus" was mapped to unknown.',
    );
    expect(result.evidence.status).toBe("evidence_incomplete");
  });

  it("keeps unavailable attachment paths explicitly marked as missing", () => {
    const report = requireReport(
      normalizePlaywrightReport(generatedFixture, fixtureOptions),
    );
    const attachment = report.tests[1]?.attachments[0];

    expect(attachment?.sourcePath).toContain("error-context.md");
    expect(attachment?.missing).toBe(true);
  });

  it("does not substitute zero for a missing duration", () => {
    const input = playwrightJsonReportSchema.parse(
      structuredClone(generatedFixture),
    );
    delete firstResult(input).duration;
    const report = requireReport(
      normalizePlaywrightReport(input, fixtureOptions),
    );

    expect(report.tests[0]?.durationMs).toBeUndefined();
    expect(report.aggregate.totalAttemptDurationMs).toBeUndefined();
  });

  it("marks missing summary fields and test results as incomplete", () => {
    const missingStats = playwrightJsonReportSchema.parse(
      structuredClone(generatedFixture),
    );
    delete missingStats.stats.expected;
    const statsResult = requireReport(
      normalizePlaywrightReport(missingStats, fixtureOptions),
    );
    expect(statsResult.metadata.missingRequiredFields).toContain(
      "stats.expected",
    );
    expect(statsResult.evidence.status).toBe("evidence_incomplete");

    const missingResults = structuredClone(generatedFixture);
    const parsed = playwrightJsonReportSchema.parse(missingResults);
    const testCase = parsed.suites[0]?.specs?.[0]?.tests?.[0];
    if (!testCase) {
      throw new Error("Generated fixture has no first test case.");
    }
    delete testCase.results;
    const resultsResult = requireReport(
      normalizePlaywrightReport(parsed, fixtureOptions),
    );
    expect(resultsResult.tests[0]?.status).toBe("unknown");
    expect(resultsResult.metadata.missingRequiredFields).toContain(
      "report.spec.ts › passes normally.results",
    );
    expect(resultsResult.evidence.status).toBe("evidence_incomplete");
  });

  it("handles a valid zero-test report as incomplete evidence", () => {
    const report = requireReport(
      normalizePlaywrightReport(zeroTestsFixture, fixtureOptions),
    );

    expect(report.aggregate.totalLogicalTests).toBe(0);
    expect(report.aggregate.totalAttempts).toBe(0);
    expect(report.evidence.status).toBe("evidence_incomplete");
    expect(report.evidence.reasons).toContain("The report contains no tests.");
  });

  it("creates stable IDs from test identity rather than array position", () => {
    const parts = [
      "test",
      "checkout.spec.ts",
      "Checkout",
      "submits",
      "chromium",
    ];
    expect(createStableId(parts)).toBe(createStableId(parts));
    expect(createStableId(parts)).not.toBe(
      createStableId([...parts.slice(0, -1), "firefox"]),
    );

    const original = playwrightJsonReportSchema.parse(
      structuredClone(generatedFixture),
    );
    const shifted = structuredClone(original);
    const originalId = requireReport(
      normalizePlaywrightReport(original, fixtureOptions),
    ).tests[0]?.id;
    shifted.suites[0]!.specs![0]!.line = 80;
    const shiftedId = requireReport(
      normalizePlaywrightReport(shifted, fixtureOptions),
    ).tests[0]?.id;
    expect(shiftedId).toBe(originalId);
  });
});

describe("evidence rules", () => {
  function reportWithStatuses(statuses: TestStatus[]): NormalizedReport {
    const base = requireReport(
      normalizePlaywrightReport(generatedFixture, fixtureOptions),
    );

    return {
      ...base,
      metadata: {
        ...base.metadata,
        isPartial: false,
        missingRequiredFields: [],
        runOutcome: "passed",
      },
      tests: statuses.map((status, index) => ({
        ...base.tests[index % base.tests.length]!,
        id: `test-${index}`,
        status,
      })),
      checklist: [],
    };
  }

  it("requires review for failing tests and failed checklist items", () => {
    const failedTest = reportWithStatuses(["failed"]);
    expect(calculateEvidenceStatus(failedTest).status).toBe("review_required");

    const failedChecklist = reportWithStatuses(["passed"]);
    failedChecklist.checklist = [
      {
        id: "data",
        label: "Test data reviewed",
        status: "fail",
        required: true,
      },
    ];
    expect(calculateEvidenceStatus(failedChecklist).status).toBe(
      "review_required",
    );
  });

  it("returns the disclaimer when all tests and required checks are clear", () => {
    const report = reportWithStatuses(["passed", "skipped"]);
    report.checklist = [
      {
        id: "data",
        label: "Test data reviewed",
        status: "not_applicable",
        required: true,
      },
    ];

    expect(calculateEvidenceStatus(report)).toEqual({
      status: "no_known_blockers",
      reasons: [
        "All mapped tests passed or were skipped, the report is complete, and all required checklist items were marked pass or not applicable.",
      ],
    });
  });

  it("marks unchecked required checklist items as incomplete", () => {
    const report = reportWithStatuses(["passed"]);
    report.checklist = [
      {
        id: "data",
        label: "Test data reviewed",
        status: "not_checked",
        required: true,
      },
    ];

    expect(calculateEvidenceStatus(report).status).toBe("evidence_incomplete");
  });

  it("explains incomplete imports, unknown outcomes, and missing checklist labels", () => {
    const partial = reportWithStatuses(["passed"]);
    partial.metadata.isPartial = true;
    partial.metadata.missingRequiredFields = ["stats.expected"];
    partial.checklist = [
      {
        id: "blank",
        label: " ",
        status: "not_applicable",
        required: false,
      },
    ];
    expect(calculateEvidenceStatus(partial)).toEqual({
      status: "evidence_incomplete",
      reasons: [
        "The imported report is partial.",
        "Required source fields are missing: stats.expected.",
        "One or more checklist items are missing a label.",
      ],
    });

    const unknownTest = reportWithStatuses(["unknown"]);
    expect(calculateEvidenceStatus(unknownTest).reasons).toContain(
      "One or more tests have an unknown status.",
    );

    const interruptedRun = reportWithStatuses(["passed"]);
    interruptedRun.metadata.runOutcome = "interrupted";
    expect(calculateEvidenceStatus(interruptedRun).reasons).toContain(
      "The Playwright run was interrupted.",
    );

    const unknownRun = reportWithStatuses(["passed"]);
    unknownRun.metadata.runOutcome = "unknown";
    expect(calculateEvidenceStatus(unknownRun).reasons).toContain(
      "The Playwright run outcome could not be determined.",
    );
  });

  it("requires review for all mapped outcomes that need human attention", () => {
    for (const status of [
      "failed",
      "timedOut",
      "interrupted",
      "flaky",
      "expectedToFail",
    ] satisfies TestStatus[]) {
      expect(calculateEvidenceStatus(reportWithStatuses([status])).status).toBe(
        "review_required",
      );
    }

    const blocker = reportWithStatuses(["passed"]);
    blocker.metadata.userReportedBlocker = true;
    expect(calculateEvidenceStatus(blocker)).toEqual({
      status: "review_required",
      reasons: ["A user marked the release notes as indicating a blocker."],
    });
  });

  it("marks an empty report incomplete", () => {
    expect(calculateEvidenceStatus(reportWithStatuses([]))).toEqual({
      status: "evidence_incomplete",
      reasons: ["The report contains no tests."],
    });
  });
});
